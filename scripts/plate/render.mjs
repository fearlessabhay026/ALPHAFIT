/**
 * Renders the plate sequence from the GLB and publishes it to the site.
 *
 *   cd scripts/plate && npm install && npm run render
 *
 * Needs only source/alphafit_bumper_20kg.glb. The embossed "20 KG" and
 * ALPHAFIT lettering live in the GLB's EXT_materials_bump texture, which
 * three.js ignores, so this script extracts it and render.html applies it.
 *
 * Writes public/plate/<hash>/fNN.webp and src/data/plate.generated.ts.
 */
import { createHash } from 'node:crypto';
import { createReadStream, existsSync } from 'node:fs';
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import http from 'node:http';
import path from 'node:path';
import { chromium } from 'playwright';
import sharp from 'sharp';
import { FRAMES, SPIN_FROM, SPIN_TO, frameSpecs } from './sequence.mjs';

const HERE = import.meta.dirname;
const ROOT = path.resolve(HERE, '../..');
const SIZE = 1000; // desktop frames
const MOBILE_SIZE = 720; // single still for phones
const MOBILE_FRAME = FRAMES - 1;

const GLB = path.join(HERE, 'source/alphafit_bumper_20kg.glb');
if (!existsSync(GLB)) throw new Error('Missing source/alphafit_bumper_20kg.glb — see scripts/plate/README.md');

/** Pulls the EXT_materials_bump texture out of the GLB as a 2048px greyscale PNG. */
async function extractBump(glb) {
  const jsonLength = glb.readUInt32LE(12);
  const gltf = JSON.parse(glb.subarray(20, 20 + jsonLength).toString('utf8'));
  const binStart = 20 + jsonLength + 8;
  const material = gltf.materials.find((m) => m.extensions?.EXT_materials_bump);
  if (!material) throw new Error('GLB has no EXT_materials_bump material');
  const texture = gltf.textures[material.extensions.EXT_materials_bump.bumpTexture.index];
  const view = gltf.bufferViews[gltf.images[texture.source].bufferView];
  const start = binStart + (view.byteOffset ?? 0);
  return sharp(glb.subarray(start, start + view.byteLength)).greyscale().resize(2048).png().toBuffer();
}
const bumpPng = await extractBump(await readFile(GLB));

// Static server: the page fetches the GLB and textures, which file:// blocks.
const MIME = { '.html': 'text/html', '.js': 'text/javascript', '.png': 'image/png', '.glb': 'model/gltf-binary' };
const server = http
  .createServer((req, res) => {
    const url = decodeURIComponent(req.url.split('?')[0]);
    if (url === '/bump.png') return res.writeHead(200, { 'content-type': 'image/png' }).end(bumpPng);
    const file = url === '/plate.glb' ? GLB : path.join(HERE, url);
    if (!file.startsWith(HERE) || !existsSync(file)) return res.writeHead(404).end();
    res.writeHead(200, { 'content-type': MIME[path.extname(file)] ?? 'application/octet-stream' });
    createReadStream(file).pipe(res);
  })
  .listen(0, '127.0.0.1');
await new Promise((r) => server.once('listening', r));
const port = server.address().port;

const browser = await chromium.launch({
  executablePath: process.env.CHROMIUM_PATH || undefined,
  args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'],
});
const page = await browser.newPage({ viewport: { width: SIZE, height: SIZE } });
page.on('pageerror', (e) => console.error('page error:', e));
await page.goto(`http://127.0.0.1:${port}/render.html?size=${SIZE}`);
await page.waitForFunction('window.ready === true', null, { timeout: 180_000 });

const pngs = [];
for (const [i, spec] of frameSpecs().entries()) {
  const url = await page.evaluate((s) => window.renderFrame(s), spec);
  pngs.push(Buffer.from(url.split(',')[1], 'base64'));
  process.stdout.write(`\rrendered ${i + 1}/${FRAMES}`);
}
await browser.close();
server.close();

const hash = createHash('sha1').update(Buffer.concat(pngs)).digest('hex').slice(0, 8);
const outRoot = path.join(ROOT, 'public/plate');
for (const old of existsSync(outRoot) ? await readdir(outRoot) : []) {
  await rm(path.join(outRoot, old), { recursive: true, force: true });
}
const outDir = path.join(outRoot, hash);
await mkdir(outDir, { recursive: true });

let total = 0;
const frames = [];
for (const [i, png] of pngs.entries()) {
  const name = `f${String(i).padStart(2, '0')}.webp`;
  const buf = await sharp(png).webp({ quality: 68, alphaQuality: 80, effort: 6 }).toBuffer();
  await writeFile(path.join(outDir, name), buf);
  frames.push(`/plate/${hash}/${name}`);
  total += buf.length;
}
const still = await sharp(pngs[MOBILE_FRAME]).resize(MOBILE_SIZE).webp({ quality: 72, alphaQuality: 80, effort: 6 }).toBuffer();
await writeFile(path.join(outDir, 'still.webp'), still);

await writeFile(
  path.join(ROOT, 'src/data/plate.generated.ts'),
  `/* eslint-disable */
// GENERATED by scripts/plate/render.mjs — do not edit by hand.

export const plateSequence = {
  size: ${SIZE},
  /** Degrees of CSS spin at scroll progress 0 and 1. Baked lighting assumes these. */
  spinFrom: ${SPIN_FROM},
  spinTo: ${SPIN_TO},
  frames: ${JSON.stringify(frames, null, 2).replace(/\n/g, '\n  ')},
  /** Single frame for phones and reduced motion. */
  still: '/plate/${hash}/still.webp',
} as const;
`,
);
console.log(`\n${FRAMES} frames, ${Math.round(total / 1024)}KB (+ still ${Math.round(still.length / 1024)}KB) -> public/plate/${hash}`);
