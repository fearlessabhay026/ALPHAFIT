/**
 * Builds responsive, cache-safe photography from the masters in assets-src/photos.
 *
 *   npm run images
 *
 * For every master it writes WebP renditions to public/images/ with a content
 * hash in the filename (so vercel.json can cache them forever), plus a tiny
 * blurred placeholder, and regenerates src/data/images.generated.ts.
 *
 * To add or replace a photograph: drop a JPEG/PNG into assets-src/photos,
 * run this script, then reference its key from src/data/site.ts.
 */
import { createHash } from 'node:crypto';
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const ROOT = path.resolve(import.meta.dirname, '..');
const SRC = path.join(ROOT, 'assets-src/photos');
const OUT = path.join(ROOT, 'public/images');
const MANIFEST = path.join(ROOT, 'src/data/images.generated.ts');

const WIDTHS = [480, 800, 1200, 1672];
/** The LCP image. Its preload is written into index.html so the fetch starts before React runs. */
const HERO = 'hero-deadlift-setup';
const HERO_SIZES = '(min-width: 1024px) 60vw, 180vw';
const QUALITY = 70;

const files = (await readdir(SRC)).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)).sort();

await rm(OUT, { recursive: true, force: true });
await mkdir(OUT, { recursive: true });

const entries = [];
let total = 0;

for (const file of files) {
  const key = path.parse(file).name;
  const input = await readFile(path.join(SRC, file));
  const hash = createHash('sha1').update(input).digest('hex').slice(0, 8);
  const { width, height } = await sharp(input).metadata();

  const widths = [...new Set(WIDTHS.map((w) => Math.min(w, width)))];
  const renditions = [];
  for (const w of widths) {
    const name = `${key}-${hash}-${w}.webp`;
    const buf = await sharp(input).resize({ width: w }).webp({ quality: QUALITY, effort: 6 }).toBuffer();
    await writeFile(path.join(OUT, name), buf);
    renditions.push({ w, url: `/images/${name}`, bytes: buf.length });
    total += buf.length;
  }

  // ~200 byte placeholder, painted blurred behind the image while it loads.
  const lqip = await sharp(input).resize({ width: 24 }).webp({ quality: 45 }).toBuffer();

  entries.push({
    key,
    width,
    height,
    src: renditions.at(-1).url,
    thumb: renditions[0].url,
    srcSet: renditions.map((r) => `${r.url} ${r.w}w`).join(', '),
    lqip: `data:image/webp;base64,${lqip.toString('base64')}`,
  });
  console.log(
    `${key.padEnd(24)} ${width}x${height}  ` +
      renditions.map((r) => `${r.w}w ${Math.round(r.bytes / 1024)}KB`).join('  '),
  );
}

const body = `/* eslint-disable */
// GENERATED by scripts/build-images.mjs — do not edit by hand. Run \`npm run images\`.

export type Photo = {
  width: number;
  height: number;
  src: string;
  /** Smallest rendition — for blurred ambience layers where resolution is irrelevant. */
  thumb: string;
  srcSet: string;
  /** Tiny blurred placeholder, shown while the real image loads. */
  lqip: string;
};

export const photos = {
${entries
  .map(
    (e) => `  '${e.key}': {
    width: ${e.width},
    height: ${e.height},
    src: '${e.src}',
    thumb: '${e.thumb}',
    srcSet: '${e.srcSet}',
    lqip: '${e.lqip}',
  },`,
  )
  .join('\n')}
} satisfies Record<string, Photo>;

export type PhotoKey = keyof typeof photos;
`;
await writeFile(MANIFEST, body);
console.log(`\n${entries.length} photos, ${Math.round(total / 1024)}KB across all renditions -> ${path.relative(ROOT, MANIFEST)}`);

const hero = entries.find((e) => e.key === HERO);
if (hero) {
  const indexPath = path.join(ROOT, 'index.html');
  const html = await readFile(indexPath, 'utf8');
  const tag = `<link rel="preload" as="image" fetchpriority="high" imagesrcset="${hero.srcSet}" imagesizes="${HERO_SIZES}" />`;
  const next = html.replace(
    /(<!-- hero-preload:start[^>]*-->)[\s\S]*?(\s*<!-- hero-preload:end -->)/,
    `$1\n    ${tag}$2`,
  );
  if (next === html && !html.includes(tag)) console.warn('index.html has no hero-preload markers');
  await writeFile(indexPath, next);
  console.log(`hero preload -> index.html (${HERO})`);
}

